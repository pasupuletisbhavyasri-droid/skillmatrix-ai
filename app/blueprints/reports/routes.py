# =========================================================
# GENERATE NORMAL REPORT
# =========================================================

@reports_bp.route(
    "/generate/<report_type>",
    methods=["POST"]
)
@login_required
@student_required
def generate(report_type):
    """
    Generate a normal student report.
    """

    generator = _REPORT_GENERATORS.get(
        report_type
    )

    # -----------------------------------------------------
    # Validate report type
    # -----------------------------------------------------

    if not generator:

        flash(
            "Unknown report type.",
            "danger"
        )

        return redirect(
            url_for("reports.index")
        )

    # -----------------------------------------------------
    # Generate report
    # -----------------------------------------------------

    try:

        report = generator(
            current_user
        )

        if not report:

            flash(
                f"{report_type} report could not be generated.",
                "danger"
            )

        else:

            flash(
                f"{report_type} report generated successfully!",
                "success"
            )

    except Exception as e:

        current_app.logger.exception(
            "Report generation failed"
        )

        flash(
            f"Could not generate {report_type} report: {str(e)}",
            "danger"
        )

    return redirect(
        url_for("reports.index")
    )


