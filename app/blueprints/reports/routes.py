# GENERATE CAREER REPORT
# =========================================================

@reports_bp.route(
    "/generate/career/<int:career_role_id>",
    methods=["POST"]
)
@login_required
@student_required
def generate_career(career_role_id):
    """
    Generate a report for a specific career role.
    """

    role = CareerRole.query.get_or_404(
        career_role_id
    )

    try:

        report = (
            report_service.generate_career_report(
                current_user,
                role
            )
        )

        if not report:

            flash(
                "Career report could not be generated.",
                "danger"
            )

        else:

            flash(
                f"Career report for {role.title} "
                f"generated successfully!",
                "success"
            )

    except Exception as e:

        current_app.logger.exception(
            "Career report generation failed"
        )

        flash(
            f"Could not generate career report: {str(e)}",
            "danger"
        )

    return redirect(
        url_for("reports.index")
    )


# =========================================================
# DOWNLOAD REPORT
# =========================================================

@reports_bp.route(
    "/download/<int:report_id>"
)
@login_required
@student_required
def download(report_id):
    """
    Download a PDF report belonging to the
    currently logged-in student.
    """

    # -----------------------------------------------------
    # Get report belonging ONLY to current student
    # -----------------------------------------------------

    report = (
        Report.query
        .filter_by(
            id=report_id,
            student_id=current_user.id
        )
        .first_or_404()
    )

    # -----------------------------------------------------
    # Validate database file path
    # -----------------------------------------------------

    if not report.file_path:

        flash(
            "This report does not have a PDF file.",
            "danger"
        )

        return redirect(
            url_for("reports.index")
        )

    # -----------------------------------------------------
    # Get UPLOAD_FOLDER
    # -----------------------------------------------------

    upload_folder = current_app.config.get(
        "UPLOAD_FOLDER",
        "uploads"
    )

    # Make upload folder absolute

    upload_folder = os.path.abspath(
        upload_folder
    )

    # -----------------------------------------------------
    # Normalize stored path
    # -----------------------------------------------------

    stored_path = str(
        report.file_path
    ).replace(
        "\\",
        "/"
    ).strip()

    # -----------------------------------------------------
    # Remove leading slash if present
    # -----------------------------------------------------

    stored_path = stored_path.lstrip("/")

    # -----------------------------------------------------
    # Handle:
    #
    # uploads/reports/file.pdf
    #
    # and:
    #
    # reports/file.pdf
    #
    # -----------------------------------------------------

    if stored_path.startswith(
        "uploads/"
    ):

        stored_path = stored_path[
            len("uploads/"):
        ]

    # -----------------------------------------------------
    # Build absolute path
    # -----------------------------------------------------

    absolute_path = os.path.abspath(
        os.path.join(
            upload_folder,
            stored_path
        )
    )

    # -----------------------------------------------------
    # Security check
    #
    # Prevent ../ path traversal
    # -----------------------------------------------------

    try:

        common_path = os.path.commonpath(
            [
                upload_folder,
                absolute_path
            ]
        )

    except ValueError:

        common_path = ""

    if common_path != upload_folder:

        current_app.logger.error(
            "Invalid report file path: %s",
            absolute_path
        )

        flash(
            "Invalid report file path.",
            "danger"
        )

        return redirect(
            url_for("reports.index")
        )

    # -----------------------------------------------------
    # Check PDF exists
    # -----------------------------------------------------

    if not os.path.isfile(
        absolute_path
    ):

        current_app.logger.error(
            "Report file not found: %s",
            absolute_path
        )

        flash(
            "Report PDF was not found. "
            "Please generate the report again.",
            "danger"
        )

        return redirect(
            url_for("reports.index")
        )

    # -----------------------------------------------------
    # Download PDF
    # -----------------------------------------------------

    return send_file(
        absolute_path,
        mimetype="application/pdf",
        as_attachment=True,
        download_name=os.path.basename(
            absolute_path
        )
    )