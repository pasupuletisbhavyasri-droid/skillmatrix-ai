"""
SkillMatrix AI - Reports Routes

Features:
- View report history
- Generate reports
- Generate career-specific reports
- Download generated PDF reports
"""

import os

from flask import (
    render_template,
    redirect,
    url_for,
    flash,
    send_file,
    current_app,
)

from flask_login import login_required, current_user

from app.blueprints.reports import reports_bp
from app.utils.decorators import student_required
from app.models import Report, CareerRole
from app.services import report_service


# =========================================================
# REPORT HISTORY
# =========================================================

@reports_bp.route("/")
@login_required
@student_required
def index():
    """
    Display all reports generated by the logged-in student.
    """

    reports = (
        Report.query
        .filter_by(
            student_id=current_user.id
        )
        .order_by(
            Report.generated_at.desc()
        )
        .all()
    )

    careers = (
        CareerRole.query
        .filter_by(
            is_active=True
        )
        .order_by(
            CareerRole.title
        )
        .all()
    )

    return render_template(
        "reports/index.html",
        reports=reports,
        careers=careers,
    )


